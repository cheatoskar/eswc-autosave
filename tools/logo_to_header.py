"""Turns the Legacy Essentials logo PNG into src/logo_rgba.h (raw RGBA, for the menu header).

    python tools/logo_to_header.py <legacy-64.png> src/logo_rgba.h

Needs Pillow. The PNG comes from the logo set (legacy-64.png); the header is committed, so a normal build does not
need Pillow or the PNG.
"""
import hashlib
import sys

from PIL import Image


def main() -> int:
    src, dst = sys.argv[1], sys.argv[2]
    raw = open(src, "rb").read()
    img = Image.open(src).convert("RGBA")
    w, h = img.size
    data = img.tobytes()
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    with open(dst, "w", newline="\r\n") as f:
        f.write("// Generated by tools/logo_to_header.py from the Legacy Essentials logo (%s, sha256 %s).\n"
                % (src.replace("\\", "/").split("/")[-1], hashlib.sha256(raw).hexdigest()[:16]))
        f.write("#pragma once\n\n")
        f.write("constexpr int kLogoW = %d, kLogoH = %d;\n" % (w, h))
        f.write("const unsigned char kLogoRgba[%d] = {\n" % len(data))
        f.write("\n".join(lines))
        f.write("\n};\n")
    print("%s: %dx%d -> %s" % (src, w, h, dst))
    return 0


if __name__ == "__main__":
    sys.exit(main())
